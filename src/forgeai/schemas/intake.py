"""Schemas for business brief intake, clarifying interviews, and groundability checks."""

from __future__ import annotations

from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, field_validator


class DocumentInput(BaseModel):
    """Metadata describing a single source document ingested by the factory."""

    doc_id: str = Field(..., min_length=1, description="Deterministic identifier for the document.")
    file_name: str = Field(..., min_length=1)
    file_path: Path
    file_type: str = Field(..., description="Normalized file extension such as .pdf, .csv, .txt, .md.")
    size_bytes: int = Field(default=0, ge=0)
    unit_count: int = Field(
        default=0,
        ge=0,
        description="Number of logical source units (e.g., PDF pages, CSV row groups, or text sections).",
    )
    metadata: dict[str, Any] = Field(default_factory=dict)


class BriefInput(BaseModel):
    """Domain-independent factory input consisting of a business brief and document folder."""

    brief_text: str = Field(..., min_length=10, description="Unseen business brief describing the desired agent.")
    documents_dir: Path = Field(..., description="Directory containing the grounding documents.")
    run_id: str | None = Field(default=None, description="Optional caller-supplied run identifier.")
    documents: list[DocumentInput] = Field(default_factory=list)

    @field_validator("brief_text")
    @classmethod
    def _strip_brief(cls, value: str) -> str:
        cleaned = value.strip()
        if len(cleaned) < 10:
            raise ValueError("brief_text must contain at least 10 non-whitespace characters.")
        return cleaned


class ClarifyingQuestion(BaseModel):
    """A single clarifying question produced by the intake interviewer."""

    question_id: str = Field(..., min_length=1)
    question: str = Field(..., min_length=5)
    rationale: str = Field(..., min_length=5)
    target_field: str = Field(
        ...,
        description="Requirement field this question resolves (e.g. scope, audience, tone, must_refuse_topics).",
    )


class ClarifyingQuestionBatch(BaseModel):
    """Structured batch of clarifying questions generated by the Intake Interviewer."""

    questions: list[ClarifyingQuestion] = Field(default_factory=list, max_length=5)
    summary_notes: str = Field(
        default="",
        description="Brief note on what is already clear from the brief and documents.",
    )


class ClarifyingAnswer(BaseModel):
    """User response paired with a clarifying question."""

    question_id: str = Field(..., min_length=1)
    question: str = Field(..., min_length=1)
    answer: str = Field(..., min_length=1)


class StructuredRequirements(BaseModel):
    """Structured specification distilled from the brief and up to five clarifying Q&As."""

    domain_name: str = Field(..., min_length=2, description="Short inferred label for the problem domain.")
    purpose: str = Field(default="", description="Core objective and value proposition of the agent.")
    scope: str = Field(..., min_length=5, description="Operational boundary of what the agent handles.")
    audience: str = Field(..., min_length=2, description="Primary end users of the generated agent.")
    tone: str = Field(..., min_length=2, description="Expected communication style and register.")
    must_answer_topics: list[str] = Field(..., min_length=1)
    must_refuse_topics: list[str] = Field(default_factory=list)
    expected_response_behavior: str = Field(
        default="",
        description="Expected citation style, uncertainty handling, and refusal behavior.",
    )
    constraints: list[str] = Field(default_factory=list)
    assumptions: list[str] = Field(default_factory=list)
    clarifying_qa: list[ClarifyingAnswer] = Field(default_factory=list, max_length=5)

    @field_validator("must_answer_topics")
    @classmethod
    def _non_empty_topics(cls, value: list[str]) -> list[str]:
        cleaned = [item.strip() for item in value if item.strip()]
        if not cleaned:
            raise ValueError("must_answer_topics must contain at least one non-empty topic.")
        return cleaned


class GroundabilityVerdict(str, Enum):
    """Support level for a topic or overall requirement against the supplied corpus."""

    SUPPORTED = "supported"
    PARTIALLY_SUPPORTED = "partially_supported"
    UNSUPPORTED = "unsupported"


class GroundabilityFinding(BaseModel):
    """Evidence check for an individual required topic against indexed source documents."""

    topic: str = Field(..., min_length=1)
    verdict: GroundabilityVerdict
    is_out_of_scope: bool = Field(
        default=False,
        description="True when the topic represents an out-of-scope/refusal boundary rather than missing corpus evidence.",
    )
    supporting_sources: list[str] = Field(default_factory=list)
    evidence_summary: str = Field(..., min_length=1)
    gap_description: str | None = None


class GroundabilityReport(BaseModel):
    """Output of the Groundability Guard verifying corpus coverage before agent generation."""

    overall_verdict: GroundabilityVerdict
    can_proceed: bool
    approval_required: bool = False
    approved_with_gaps: bool = False
    findings: list[GroundabilityFinding] = Field(default_factory=list)
    ungrounded_topics: list[str] = Field(default_factory=list)
    out_of_scope_topics: list[str] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)

